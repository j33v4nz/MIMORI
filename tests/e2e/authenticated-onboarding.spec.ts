import { test, expect, type Page } from '@playwright/test';
import { createClient } from '@supabase/supabase-js';
import { randomBytes, randomUUID } from 'node:crypto';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';

const execute = promisify(execFile);
const supabaseURL = process.env.NEXT_PUBLIC_SUPABASE_URL!;
const serviceKey = process.env.SUPABASE_SERVICE_ROLE_KEY!;
const mailpitURL = process.env.MIMORI_MAILPIT_URL || 'http://127.0.0.1:54324';
const createdUserIds = new Set<string>();
const createdOrgIds = new Set<string>();
const createdKeyIds = new Set<string>();
const ownedEmails = new Set<string>();
const ownMessages = new Set<string>();
const admin = createClient(supabaseURL, serviceKey, { auth: { persistSession: false } });

async function trackUser(email: string) {
  const { data, error } = await admin.auth.admin.listUsers({ page: 1, perPage: 1000 });
  if (error) throw error;
  const user = data.users.find(user => user.email === email);
  if (!user) throw new Error('Smoke user was not provisioned');
  createdUserIds.add(user.id);
  const memberships = await admin.from('org_members').select('org_id').eq('user_id', user.id);
  if (memberships.error) throw memberships.error;
  for (const row of memberships.data || []) createdOrgIds.add(row.org_id);
  return user;
}

async function confirmationLink(email: string) {
  let result: string | undefined;
  await expect.poll(async () => {
    const listing = await fetch(`${mailpitURL}/api/v1/messages`).then(response => response.json());
    const message = listing.messages?.find((message: { ID: string; To: Array<{ Address: string }> }) =>
      message.To?.some(recipient => recipient.Address === email));
    if (!message) return false;
    ownMessages.add(message.ID);
    const detail = await fetch(`${mailpitURL}/api/v1/message/${message.ID}`).then(response => response.json());
    const content = `${detail.HTML || ''} ${detail.Text || ''}`;
    result = content.match(/https?:[^"\s<>]+\/auth\/v1\/verify[^"\s<>]+/)?.[0]?.replaceAll('&amp;', '&');
    return Boolean(result);
  }, { timeout: 30_000 }).toBe(true);
  return result!;
}

async function signin(page: Page, email: string, password: string) {
  await page.goto('/login');
  await page.locator('#login-email').fill(email);
  await page.locator('#login-password').fill(password);
  await page.getByRole('button', { name: /Sign In to Dashboard/ }).click();
  await expect(page).not.toHaveURL(/\/login/);
}

test.beforeAll(() => {
  expect(new URL(supabaseURL).hostname).toMatch(/^(localhost|127\.0\.0\.1)$/);
  expect(new URL(mailpitURL).hostname).toMatch(/^(localhost|127\.0\.0\.1)$/);
});

test.afterAll(async () => {
  // Only IDs from unique emails generated by this test may be removed.
  // Never reset the database or clear shared Mailpit messages.
  for (const email of ownedEmails) {
    const users = await admin.auth.admin.listUsers({ page: 1, perPage: 1000 });
    const user = users.data.users.find(user => user.email === email);
    if (user) await trackUser(email);
  }
  for (const id of createdKeyIds) {
    // Counters in older schemas lack a cascading key foreign key.
    await execute('docker', ['exec', 'supabase_db_mimori', 'psql', '-U', 'postgres', '-d', 'postgres', '-v', 'ON_ERROR_STOP=1', '-c', `DELETE FROM public.rate_limit_counters WHERE api_key_id = '${id}';`]);
  }
  for (const id of createdOrgIds) {
    const members = await admin.from('org_members').select('user_id').eq('org_id', id);
    if (members.error) throw members.error;
    if (members.data.some(member => !createdUserIds.has(member.user_id))) {
      throw new Error('Refusing to delete an organization containing another user');
    }
    const result = await admin.from('organizations').delete().eq('id', id);
    if (result.error) throw result.error;
  }
  for (const id of createdUserIds) {
    const result = await admin.auth.admin.deleteUser(id);
    if (result.error) throw result.error;
  }
  if (ownMessages.size) {
    await fetch(`${mailpitURL}/api/v1/messages`, {
      method: 'DELETE', headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ IDs: [...ownMessages] })
    });
  }
});

