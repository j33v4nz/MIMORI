test('a real invite email verifies a unique account through the auth callback', async ({ page }, testInfo) => {
  const email = `mimori-invite-smoke-${randomUUID()}@example.invalid`;
  ownedEmails.add(email);
  const invitation = await admin.auth.admin.inviteUserByEmail(email, {
    redirectTo: `${testInfo.project.use.baseURL}/auth/callback`
  });
  if (invitation.error) throw invitation.error;
  await trackUser(email);
  const link = await confirmationLink(email);
  await page.goto(link);
  // GoTrue invite links can return fragment tokens instead of PKCE auth codes.
  // Set a unique password for this invited test user, then verify real sign-in.
  const user = await trackUser(email);
  const refreshed = await admin.auth.admin.getUserById(user.id);
  expect(refreshed.data.user?.email_confirmed_at).toBeTruthy();
  const password = `Invite!${randomBytes(24).toString('hex')}`;
  const updated = await admin.auth.admin.updateUserById(user.id, { password });
  if (updated.error) throw updated.error;
  await signin(page, email, password);
  await page.goto('/keys');
  await expect(page.locator('#key-label')).toBeVisible();
});
